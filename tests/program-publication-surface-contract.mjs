import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import * as cheerio from "cheerio";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(import.meta.dirname, "..");
const SITE = "https://atelierdeconsultanta.ro";
const { isPublicProgram, loadProgramConfig } = require("../tools/program-factual-governance");
const { fileForRoute, sitemapRoutes } = require("../tools/structured-data-utils");
const { programs } = loadProgramConfig();
const publicPrograms = programs.filter((program) => isPublicProgram(program) && program.discovery?.listed !== false && !program.discovery?.redirectTarget);
const sitemap = new Set(sitemapRoutes(ROOT));
const banners = JSON.parse(fs.readFileSync(path.join(ROOT, "banners.json"), "utf8"));
const bannerIds = new Set(banners.map((banner) => banner.programId));
const homepage = cheerio.load(fs.readFileSync(path.join(ROOT, "index.html"), "utf8"), { decodeEntities: false });
const carouselIds = new Set(homepage("[data-priority-slide]").map((_, element) => homepage(element).attr("data-program-id")).get());
const watermarkPattern = /(?:chatgpt|openai|generated by ai|ai[- ]generated|răspuns generativ|raspuns generativ|generat(?:ă|a|e) (?:de|cu) (?:ai|inteligență artificială)|ca model de limbaj|as an ai)/iu;

assert.equal(publicPrograms.length, 19, "registrul trebuie să conțină 19 programe publice, listate și canonice");
assert.equal(banners.length, publicPrograms.length, "fiecare program public trebuie să aibă exact un banner");
assert.equal(carouselIds.size, publicPrograms.length, "homepage-ul trebuie să afișeze fiecare program public în carusel");

for (const program of publicPrograms) {
  const file = fileForRoute(ROOT, program.pageUrl);
  assert(fs.existsSync(file), `${program.slug}: fișierul paginii lipsește`);
  const html = fs.readFileSync(file, "utf8");
  const $ = cheerio.load(html, { decodeEntities: false });
  const canonical = $("link[rel='canonical']").first().attr("href");
  const visibleText = $("body").clone().find("script, style, template, noscript").remove().end().text().replace(/\s+/gu, " ").trim();

  assert.equal(canonical, `${SITE}${program.pageUrl}`, `${program.slug}: canonical incorect`);
  assert(sitemap.has(program.pageUrl), `${program.slug}: pagina lipsește din sitemap`);
  assert(bannerIds.has(program.slug), `${program.slug}: banner absent`);
  assert(carouselIds.has(program.slug), `${program.slug}: slide absent din carusel`);
  assert(!watermarkPattern.test(visibleText), `${program.slug}: urmă de răspuns generativ în conținutul vizibil`);
}

assert.equal(new Set(banners.map((banner) => banner.programId)).size, banners.length, "bannerele nu trebuie duplicate");
console.log(`Program publication surfaces PASS: ${publicPrograms.length} pagini, canonical, sitemap, bannere, carusel și zero watermark-uri AI.`);
